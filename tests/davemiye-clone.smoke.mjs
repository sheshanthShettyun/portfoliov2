const countGifFrames = (asset) => {
  let offset = 13;
  const packed = asset[10];
  if (packed & 0x80) offset += 3 * (2 ** ((packed & 0x07) + 1));

  let frames = 0;
  while (offset < asset.length) {
    const block = asset[offset++];
    if (block === 0x3b) break;
    if (block === 0x21) {
      offset += 1;
      offset += 1 + asset[offset];
      while (offset < asset.length) {
        const size = asset[offset++];
        if (size === 0) break;
        offset += size;
      }
      continue;
    }
    if (block !== 0x2c) break;

    frames += 1;
    const descriptorPacked = asset[offset + 8];
    offset += 9;
    if (descriptorPacked & 0x80) offset += 3 * (2 ** ((descriptorPacked & 0x07) + 1));
    offset += 1;
    while (offset < asset.length) {
      const size = asset[offset++];
      if (size === 0) break;
      offset += size;
    }
  }
  return frames;
};

